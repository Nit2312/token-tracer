/**
 * REAL-concurrency tests for runResearchRollup (advisory lock + single transaction), on several simultaneous connections.
 * Temp tables are per-connection, so this suite needs real (committed) tables. It therefore creates a uniquely named SCRATCH SCHEMA on
 * the explicit test branch, never touches `public`, and drops the schema afterwards. Configuration: tests/README.md
 * (TEST_DATABASE_URL, direct/non-pooled, + TEST_DATABASE_EXPECTED_ENDPOINT). Fails if missing; never reads any env file.
 */
import { SKIP_DB, SKIP_REASON, connectionString, loadTestDb } from './helpers/test-db'; // FIRST: installs the production-credential tripwire
import { after, before, describe, it } from 'node:test';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import pg from 'pg';
import { ROLLUP_ADVISORY_LOCK_KEY, runResearchRollup, UNATTRIBUTED_USER_ID } from '../lib/team/research';

const cfg = SKIP_DB ? undefined : loadTestDb('owner'); // direct, endpoint-verified test branch; throws immediately if not configured

const schema = `tt_rollup_${crypto.randomBytes(6).toString('hex')}`;
const uuid = () => crypto.randomUUID();
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
const conns: pg.Client[] = [];

async function connect(): Promise<pg.Client> {
  const c = new pg.Client({ connectionString: connectionString(cfg!), ssl: { rejectUnauthorized: false } });
  await c.connect();
  await c.query(`SET search_path = ${schema}`); // ONLY the scratch schema: an unqualified table can never resolve to public
  conns.push(c);
  return c;
}

describe('rollup concurrency (scratch schema, opt-in)', { skip: SKIP_DB && SKIP_REASON }, () => {
  let admin: pg.Client;
  const sessions: { team: string; member: string; sid: string }[] = [];
  const histKeys: { team: string; sid: string }[] = [];
  let sentinelWithCounterpart = 0;

  before(async () => {
    admin = await connect();
    await admin.query(`CREATE SCHEMA ${schema}`); // fails loudly if it somehow exists
    await admin.query(`
      CREATE TABLE ${schema}.sync_sessions (LIKE public.sync_sessions INCLUDING ALL);
      CREATE TABLE ${schema}.sync_session_files (LIKE public.sync_session_files INCLUDING ALL);
      CREATE TABLE ${schema}.session_turns (LIKE public.session_turns INCLUDING ALL EXCLUDING DEFAULTS);
      ALTER TABLE ${schema}.session_turns ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
      CREATE TABLE ${schema}.session_outcomes (session_id text NOT NULL, org_id text NOT NULL, user_id text NOT NULL, tool text NOT NULL, model text NOT NULL,
        intent_category text, total_input_tokens int, total_output_tokens int, total_cost numeric(12,4), files_touched int, lines_changed int,
        tool_call_count int, had_rework boolean, had_revert boolean, had_tool_error boolean, success boolean, complexity_score numeric,
        PRIMARY KEY (org_id, user_id, tool, session_id));`);
    // 40 live sessions (2 turns each) across 4 teams; 10 of them also have a legacy nil-UUID outcome that must be replaced.
    for (let i = 0; i < 40; i++) {
      const s = { team: uuid(), member: uuid(), sid: `sid-${uuid()}` };
      sessions.push(s);
      await admin.query(`INSERT INTO sync_sessions (team_id, member_id, source, session_id, model, payload_hash, api_cost) VALUES ($1,$2,'cursor',$3,'m','h',$4)`, [s.team, s.member, s.sid, i]);
      for (const [idx, role] of [[0, 'user'], [0, 'assistant']] as const) {
        await admin.query(`INSERT INTO session_turns (session_id, org_id, user_id, tool, model, turn_index, turn_role, input_tokens, lines_added, lines_removed, tool_call_count)
                           VALUES ($1,$2,$3,'cursor','m',$4,$5,$6,$7,0,$8)`, [s.sid, s.team, s.member, idx, role, 10 + i, i, i % 5]); // scratch copy has no column defaults, so set every aggregated column
      }
      if (i < 10) {
        sentinelWithCounterpart++;
        await admin.query(`INSERT INTO session_outcomes (session_id, org_id, user_id, tool, model) VALUES ($1,$2,$3,'cursor','m')`, [s.sid, s.team, UNATTRIBUTED_USER_ID]);
      }
    }
    // 10 historical orphans (no turns, no sessions) that must all survive.
    for (let i = 0; i < 10; i++) {
      const h = { team: uuid(), sid: `hist-${uuid()}` };
      histKeys.push(h);
      await admin.query(`INSERT INTO session_outcomes (session_id, org_id, user_id, tool, model, files_touched, lines_changed, tool_call_count) VALUES ($1,$2,$3,'cursor','m',$4,$4,$4)`, [h.sid, h.team, UNATTRIBUTED_USER_ID, i]);
    }
  });

  after(async () => {
    try { await admin?.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`); } catch { /* reported below */ }
    await Promise.all(conns.map((c) => c.end().catch(() => {})));
  });

  const total = async () => Number((await admin.query('SELECT count(*) FROM session_outcomes')).rows[0].count);
  const assertFinalState = async () => {
    // 40 attributed (one per live session) + 10 historical orphans; the 10 replaced sentinels are gone; no duplicates.
    assert.equal(await total(), 50);
    assert.equal(Number((await admin.query('SELECT count(*) FROM session_outcomes WHERE user_id = $1', [UNATTRIBUTED_USER_ID])).rows[0].count), 10);
    assert.equal(Number((await admin.query('SELECT count(*) FROM (SELECT 1 FROM session_outcomes GROUP BY org_id, user_id, tool, session_id HAVING count(*) > 1) d')).rows[0].count), 0);
    const live = (await admin.query('SELECT session_id, org_id, user_id FROM session_outcomes WHERE user_id <> $1', [UNATTRIBUTED_USER_ID])).rows;
    assert.equal(live.length, 40);
    for (const s of sessions) assert.ok(live.some((r) => r.session_id === s.sid && r.org_id === s.team && r.user_id === s.member));
    for (const h of histKeys) assert.equal(Number((await admin.query('SELECT count(*) FROM session_outcomes WHERE session_id = $1 AND org_id = $2', [h.sid, h.team])).rows[0].count), 1);
    assert.equal(Number((await admin.query('SELECT count(*) FROM session_outcomes WHERE complexity_score IS NULL')).rows[0].count), 0);
  };

  it('six simultaneous rollups all succeed and converge on exactly one correct set of outcomes', async () => {
    assert.equal(sentinelWithCounterpart, 10);
    const clients = await Promise.all(Array.from({ length: 6 }, () => connect()));
    const results = await Promise.allSettled(clients.map((c) => runResearchRollup({ executor: c })));
    assert.deepEqual(results.filter((r) => r.status === 'rejected').map((r) => String((r as PromiseRejectedResult).reason)), []);
    await assertFinalState();
    const snapshot = JSON.stringify((await admin.query('SELECT org_id, user_id, tool, session_id, complexity_score::float FROM session_outcomes ORDER BY 1,2,3,4')).rows);
    await runResearchRollup({ executor: clients[0] }); // a later run is a no-op
    assert.equal(JSON.stringify((await admin.query('SELECT org_id, user_id, tool, session_id, complexity_score::float FROM session_outcomes ORDER BY 1,2,3,4')).rows), snapshot);
  });

  it('the advisory lock really serializes rollups: a second rollup waits for the holder, then runs', async () => {
    const holder = await connect(); const runner = await connect();
    const before = await total();
    await holder.query('BEGIN');
    await holder.query('SELECT pg_advisory_xact_lock($1::bigint)', [ROLLUP_ADVISORY_LOCK_KEY]);
    // a legacy sentinel the blocked rollup should replace once it gets to run
    const s = sessions[20];
    await admin.query(`INSERT INTO session_outcomes (session_id, org_id, user_id, tool, model) VALUES ($1,$2,$3,'cursor','m') ON CONFLICT DO NOTHING`, [s.sid, s.team, UNATTRIBUTED_USER_ID]);
    let done = false;
    const p = runResearchRollup({ executor: runner }).then(() => { done = true; });
    await sleep(600);
    assert.equal(done, false); // blocked behind the lock holder
    assert.equal(await total(), before + 1); // and it has changed nothing yet
    await holder.query('COMMIT'); // release
    await p;
    assert.equal(done, true);
    assert.equal(await total(), before); // sentinel replaced after the lock was granted
  });
});
