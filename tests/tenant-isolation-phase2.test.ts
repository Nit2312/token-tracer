describe('Phase 1.2 — new shape (rollup, admin cleanup, reprompt events)', { skip: SKIP_DB && SKIP_REASON }, () => {
  let c: pg.Client | undefined;
  before(async () => { c = await open(NEW_SHAPE_DDL, TABLES); });
  after(async () => { await close(c); });
  const t = (name: string, fn: (c: pg.Client) => Promise<void>) => it(name, async () => { await fn(c!); });
  const nested = () => ({ executor: wrap(c!), nested: true });

  const session = async (team: string, member: string, source: string, sid: string, tokensIn = 1000, cost = 0) => {
    const { rows } = await c!.query(
      `INSERT INTO sync_sessions (team_id, member_id, source, session_id, model, tokens_in, tokens_out, api_cost, payload_hash)
       VALUES ($1,$2,$3,$4,'m',$5,100,$6,'h') RETURNING id::text AS id, session_id, team_id::text AS team_id, member_id::text AS member_id, source`,
      [team, member, source, sid, tokensIn, cost]);
    return rows[0] as SessionRow;
  };
  const count = async (table: string, org: string, usr: string, tool: string, sid: string) =>
    Number((await c!.query(`SELECT count(*) FROM ${table} WHERE org_id=$1 AND user_id=$2 AND tool=$3 AND session_id=$4`, [org, usr, tool, sid])).rows[0].count);

  t('nightly rollup with colliding session ids: one outcome per owner, own intent/cost/tokens, idempotent', async () => {
    const sid = `sid-${uuid()}`;
    const [ta, ma, tb, mb] = [uuid(), uuid(), uuid(), uuid()];
    await session(ta, ma, 'cursor', sid, 1000, 1.5); await session(tb, mb, 'cursor', sid, 9000, 7.25);
    await saveSessionTurns(ta, ma, 'cursor', 'm', sid, events(2), nested());
    await saveSessionTurns(tb, mb, 'cursor', 'm', sid, events(2), nested());
    await c!.query(`UPDATE session_turns SET intent_category = 'debug' WHERE org_id = $1 AND session_id = $2`, [ta, sid]);
    await c!.query(`UPDATE session_turns SET intent_category = 'feature' WHERE org_id = $1 AND session_id = $2`, [tb, sid]);

    await runResearchRollup(nested());
    const out = async () => (await c!.query('SELECT org_id, user_id, tool, intent_category, total_cost::float AS cost, total_input_tokens AS tin FROM session_outcomes WHERE session_id = $1 ORDER BY org_id', [sid])).rows;
    let rows = await out();
    assert.equal(rows.length, 2);
    const a = rows.find((r) => r.org_id === ta)!; const b = rows.find((r) => r.org_id === tb)!;
    assert.deepEqual([a.user_id, a.intent_category, a.cost], [ma, 'debug', 1.5]);
    assert.deepEqual([b.user_id, b.intent_category, b.cost], [mb, 'feature', 7.25]);
    assert.ok(Math.abs(a.tin - 1000) <= 3 && Math.abs(b.tin - 9000) <= 3); // each owner's own tokens

    await c!.query(`UPDATE session_turns SET intent_category = 'refactor' WHERE org_id = $1 AND session_id = $2`, [tb, sid]);
    await runResearchRollup(nested()); // re-run: upserts, no "cannot affect row a second time"
    rows = await out();
    assert.equal(rows.length, 2);
    assert.equal(rows.find((r) => r.org_id === ta)!.intent_category, 'debug'); // untouched
    assert.equal(rows.find((r) => r.org_id === tb)!.intent_category, 'refactor');
  });

  t('rollup across sources and members with one session_id keeps four separate outcomes', async () => {
    const sid = `sid-${uuid()}`;
    const [team, m1, m2] = [uuid(), uuid(), uuid()];
    for (const [m, src] of [[m1, 'cursor'], [m1, 'claude'], [m2, 'cursor'], [m2, 'claude']]) {
      await session(team, m, src, sid); await saveSessionTurns(team, m, src, 'm', sid, events(1), nested());
    }
    await runResearchRollup(nested());
    assert.equal(Number((await c!.query('SELECT count(*) FROM session_outcomes WHERE session_id = $1', [sid])).rows[0].count), 4);
  });

  t('reprompt events carry the owner, are replaced (not stacked) on re-ingest, and never touch another owner', async () => {
    const sid = `sid-${uuid()}`;
    const [ta, ma, tb, mb] = [uuid(), uuid(), uuid(), uuid()];
    await session(ta, ma, 'cursor', sid); await session(tb, mb, 'cursor', sid);
    const prev = process.env.ENABLE_REPROMPT_ANALYSIS_ORG_ID;
    try {
      process.env.ENABLE_REPROMPT_ANALYSIS_ORG_ID = tb;
      await saveSessionTurns(tb, mb, 'cursor', 'm', sid, events(3, 'same prompt text'), nested());
      process.env.ENABLE_REPROMPT_ANALYSIS_ORG_ID = ta;
      await saveSessionTurns(ta, ma, 'cursor', 'm', sid, events(3, 'same prompt text'), nested());
      assert.equal(await count('redundant_reprompt_events', ta, ma, 'cursor', sid), 2);
      assert.equal(await count('redundant_reprompt_events', tb, mb, 'cursor', sid), 2);
      await saveSessionTurns(ta, ma, 'cursor', 'm', sid, events(3, 'same prompt text'), nested()); // re-ingest A
      assert.equal(await count('redundant_reprompt_events', ta, ma, 'cursor', sid), 2); // replaced, not 4
      assert.equal(await count('redundant_reprompt_events', tb, mb, 'cursor', sid), 2); // B untouched
    } finally {
      if (prev === undefined) delete process.env.ENABLE_REPROMPT_ANALYSIS_ORG_ID; else process.env.ENABLE_REPROMPT_ANALYSIS_ORG_ID = prev;
    }
    // prompt deletion by team A removes only A's reprompt events; legacy NULL-owner rows are never matched
    await c!.query(`INSERT INTO redundant_reprompt_events (session_id, turn_index) VALUES ($1, 1)`, [sid]);
    await deletePrompts({ kind: 'team', teamId: ta }, { ids: [], sessionId: sid, turnIndex: null }, nested());
    assert.equal(await count('redundant_reprompt_events', ta, ma, 'cursor', sid), 0);
    assert.equal(await count('redundant_reprompt_events', tb, mb, 'cursor', sid), 2);
    assert.equal(Number((await c!.query('SELECT count(*) FROM redundant_reprompt_events WHERE session_id = $1 AND org_id IS NULL', [sid])).rows[0].count), 1);
  });

  const outcome = (session_id: string, org: string, user: string, tool = 'cursor', files = 0) =>
    c!.query(`INSERT INTO session_outcomes (session_id, org_id, user_id, tool, model, files_touched, lines_changed, tool_call_count) VALUES ($1,$2,$3,$4,'m',$5,$5,$5)`, [session_id, org, user, tool, files]);
  const outcomesFor = async (sid: string) => (await c!.query('SELECT org_id, user_id, tool FROM session_outcomes WHERE session_id = $1 ORDER BY user_id', [sid])).rows;

  t('rollup replaces a nil-UUID legacy outcome once the owner is known — matched on (org_id, tool, session_id) only', async () => {
    const sid = `sid-${uuid()}`;
    const [team, member, otherTeam] = [uuid(), uuid(), uuid()];
    await session(team, member, 'cursor', sid); await saveSessionTurns(team, member, 'cursor', 'm', sid, events(2), nested());
    await outcome(sid, team, UNATTRIBUTED_USER_ID, 'cursor');       // legacy row for THIS session → must be replaced
    await outcome(sid, team, UNATTRIBUTED_USER_ID, 'claude');       // same org + id, other tool → must survive
    await outcome(sid, otherTeam, UNATTRIBUTED_USER_ID, 'cursor');  // same id + tool, other org → must survive
    await runResearchRollup(nested());
    const rows = await outcomesFor(sid);
    assert.equal(rows.filter((r) => r.org_id === team && r.tool === 'cursor').length, 1);
    assert.equal(rows.find((r) => r.org_id === team && r.tool === 'cursor')!.user_id, member); // only the attributed row remains
    assert.ok(rows.some((r) => r.org_id === team && r.tool === 'claude' && r.user_id === UNATTRIBUTED_USER_ID));
    assert.ok(rows.some((r) => r.org_id === otherTeam && r.user_id === UNATTRIBUTED_USER_ID));
    assert.equal(rows.length, 3);
  });

  t('historical outcomes (nil-UUID, no turns) are preserved by the rollup and still feed the complexity statistics', async () => {
    const team = uuid();
    const sids = Array.from({ length: 5 }, () => `hist-${uuid()}`);
    for (const [i, sid] of sids.entries()) await outcome(sid, team, UNATTRIBUTED_USER_ID, 'cursor', (i + 1) * 10);
    const before = Number((await c!.query('SELECT count(*) FROM session_outcomes')).rows[0].count);
    await runResearchRollup(nested());
    await runResearchRollup(nested()); // idempotent
    assert.equal(Number((await c!.query('SELECT count(*) FROM session_outcomes')).rows[0].count), before); // nothing lost or added
    const { rows } = await c!.query('SELECT session_id, complexity_score::float AS cx FROM session_outcomes WHERE session_id = ANY($1::text[]) ORDER BY files_touched', [sids]);
    assert.equal(rows.length, 5);
    assert.ok(rows.every((r) => r.cx !== null && Number.isFinite(r.cx)));
    assert.ok(rows[0].cx < rows[4].cx); // scores still ranked by the preserved rows' own values
  });

  t('rollup is atomic: a failure after the upsert (delete step, or complexity step) rolls everything back', async () => {
    for (const failAt of [/DELETE FROM session_outcomes/, /complexity_score = \(/]) {
      const sid = `sid-${uuid()}`;
      const [team, member] = [uuid(), uuid()];
      await session(team, member, 'cursor', sid); await saveSessionTurns(team, member, 'cursor', 'm', sid, events(2), nested());
      await outcome(sid, team, UNATTRIBUTED_USER_ID, 'cursor', 7);
      const failing: Queryable = { query: ((text: string, p?: unknown[]) => failAt.test(text) ? Promise.reject(new Error('simulated rollup failure')) : c!.query(text, p)) as never };
      await assert.rejects(() => runResearchRollup({ executor: failing, nested: true }), /simulated rollup failure/);
      const rows = await outcomesFor(sid);
      assert.deepEqual(rows, [{ org_id: team, user_id: UNATTRIBUTED_USER_ID, tool: 'cursor' }]); // upsert undone, sentinel intact
      await runResearchRollup(nested()); // and the next run succeeds normally
      assert.deepEqual((await outcomesFor(sid)).map((r) => r.user_id), [member]);
    }
  });

  t('the nil UUID is reserved: saveSessionTurns refuses it as team or member', async () => {
    await assert.rejects(() => saveSessionTurns(uuid(), UNATTRIBUTED_USER_ID, 'cursor', 'm', 'x', events(1), nested()), /reserved/);
    await assert.rejects(() => saveSessionTurns(UNATTRIBUTED_USER_ID, uuid(), 'cursor', 'm', 'x', events(1), nested()), /reserved/);
  });

  const seedDerived = async (r: SessionRow) => {
    await saveSessionTurns(r.team_id, r.member_id, r.source, 'm', r.session_id, events(2), nested());
    await c!.query(`INSERT INTO session_outcomes (session_id, org_id, user_id, tool, model) VALUES ($1,$2,$3,$4,'m')`, [r.session_id, r.team_id, r.member_id, r.source]);
    await c!.query(`INSERT INTO redundant_reprompt_events (session_id, org_id, user_id, tool, turn_index) VALUES ($1,$2,$3,$4,0)`, [r.session_id, r.team_id, r.member_id, r.source]);
  };
  const derived = async (r: SessionRow) => [
    await count('session_turns', r.team_id, r.member_id, r.source, r.session_id),
    await count('session_outcomes', r.team_id, r.member_id, r.source, r.session_id),
    await count('redundant_reprompt_events', r.team_id, r.member_id, r.source, r.session_id),
  ];

  t('admin delete: removes only the targeted sessions (and their derived rows) even with colliding ids', async () => {
    const sid = `sid-${uuid()}`;
    const [ta, ma, tb, mb] = [uuid(), uuid(), uuid(), uuid()];
    const a1 = await session(ta, ma, 'cursor', sid); const a2 = await session(ta, ma, 'claude', sid); const b = await session(tb, mb, 'cursor', sid);
    for (const r of [a1, a2, b]) await seedDerived(r);
    const res = await withTransaction((db) => deleteSessionsWithDerived(db, [a1]), nested());
    assert.deepEqual(res, { turnsDeleted: 4, sessionsDeleted: 1 });
    assert.deepEqual(await derived(a1), [0, 0, 0]);
    assert.deepEqual(await derived(a2), [4, 1, 1]); // same member, other source: untouched
    assert.deepEqual(await derived(b), [4, 1, 1]); // other owner, same id: untouched
    assert.equal(Number((await c!.query('SELECT count(*) FROM sync_sessions WHERE session_id = $1', [sid])).rows[0].count), 2);
  });

  t('admin reassign: moves identity-matched derived rows, drops duplicates with their derived rows, spares colliding owners', async () => {
    const sid = `sid-${uuid()}`, dupSid = `sid-${uuid()}`;
    const [ta, ma, tb, mb, tt, mt] = [uuid(), uuid(), uuid(), uuid(), uuid(), uuid()];
    const a = await session(ta, ma, 'cursor', sid); const aDup = await session(ta, ma, 'cursor', dupSid);
    const b = await session(tb, mb, 'cursor', sid); const targetOwn = await session(tt, mt, 'cursor', dupSid);
    for (const r of [a, aDup, b, targetOwn]) await seedDerived(r);
    const res = await withTransaction((db) => reassignSessionsWithDerived(db, [a, aDup], { memberId: mt, teamId: tt }), nested());
    assert.deepEqual(res, { duplicatesRemoved: 1, sessionsMoved: 1 });
    assert.deepEqual(await derived({ ...a, team_id: tt, member_id: mt }), [4, 1, 1]); // moved to the target identity
    assert.deepEqual(await derived(a), [0, 0, 0]);
    assert.deepEqual(await derived(aDup), [0, 0, 0]); // duplicate's derived rows dropped…
    assert.deepEqual(await derived(targetOwn), [4, 1, 1]); // …and the target's own copy is not duplicated or relabelled
    assert.deepEqual(await derived(b), [4, 1, 1]); // colliding owner untouched
  });

  t('admin reassign rolls back completely when a later statement fails', async () => {
    const sid = `sid-${uuid()}`;
    const [ta, ma, tt, mt] = [uuid(), uuid(), uuid(), uuid()];
    const a = await session(ta, ma, 'cursor', sid); await seedDerived(a);
    const failing: Queryable = { query: ((text: string, p?: unknown[]) =>
      /UPDATE session_outcomes/.test(text) ? Promise.reject(new Error('simulated failure')) : c!.query(text, p)) as never };
    await assert.rejects(() => withTransaction((db) => reassignSessionsWithDerived(db, [a], { memberId: mt, teamId: tt }), { executor: failing, nested: true }), /simulated failure/);
    assert.deepEqual(await derived(a), [4, 1, 1]); // nothing relabelled
    const { rows } = await c!.query('SELECT team_id::text AS t, member_id::text AS m FROM sync_sessions WHERE id = $1', [a.id]);
    assert.deepEqual(rows[0], { t: ta, m: ma }); // the session row itself was not moved either
  });
});

