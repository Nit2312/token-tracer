/** Open one connection + transaction with the given TEMP tables. Any failure throws: an unreachable test database is a failure, not a skip. */
async function open(ddl: string, tables: string[]): Promise<pg.Client> {
  const c = new pg.Client({ connectionString: connectionString(cfg!), ssl: { rejectUnauthorized: false } });
  try {
    await c.connect();
    await c.query('BEGIN');
    await c.query(ddl);
    const { rows } = await c.query(`SELECT bool_and(to_regclass(t)::oid = to_regclass('pg_temp.' || t)::oid) AS ok FROM unnest($1::text[]) AS t`, [tables]);
    assert.equal(rows[0].ok, true); // unqualified names resolve to the temp copies, never the real tables
    return c;
  } catch (err) {
    await c.query('ROLLBACK').catch(() => {}); await c.end().catch(() => {});
    throw err;
  }
}
async function close(c?: pg.Client) { if (c) { await c.query('ROLLBACK').catch(() => {}); await c.end().catch(() => {}); } }
