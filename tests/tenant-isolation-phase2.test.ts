  let c: pg.Client | undefined;
  const migration = () => fs.readFileSync('scripts/migrations/tenant-isolation.sql', 'utf8')
    // keep the holding table in the temp schema so the test never creates a real table
    .replace('CREATE TABLE IF NOT EXISTS session_outcomes_unattributed', 'CREATE TEMP TABLE IF NOT EXISTS session_outcomes_unattributed');
