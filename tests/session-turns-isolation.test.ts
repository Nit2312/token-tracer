/**
 * Tenant-isolation regression tests for session_turns (saveSessionTurns, prompt deletion, assistant-turn join).
 *
 * Runs against the real PostgreSQL engine but NEVER touches real tables or data: everything happens in ONE transaction
 * on a single connection, against TEMP copies of the tables (they shadow the real ones via pg_temp), and the
 * transaction is rolled back at the end. Skipped unless DATABASE_URL / NEON_CONNECTION_STRING is set and reachable.
 * Prompt text in these tests is synthetic and is never printed.
 */
import { after, before, describe, it } from 'node:test';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import pg from 'pg';
import { SKIP_DB, SKIP_REASON, connectionString, loadTestDb } from './helpers/test-db'; // FIRST: installs the production-credential tripwire
import { saveSessionTurns } from '../lib/team/research';
import { deletePrompts, PromptDeleteError } from '../lib/team/prompt-delete';
import { ASSISTANT_TURN_JOIN, SESSION_TURN_OWNER_JOIN } from '../lib/team/prompt-sql';
import type { Queryable } from '../lib/team/db';

const cfg = SKIP_DB ? undefined : loadTestDb('owner'); // throws immediately with a clear message when the test branch is not configured
let client: pg.Client | undefined;
const uuid = () => crypto.randomUUID();
const db = (): Queryable => ({ query: (text: string, params?: unknown[]) => client!.query(text, params) as never });
const nested = () => ({ executor: db(), nested: true });

async function newSession(team: string, member: string, source: string, sid: string, tokensIn = 1000, tokensOut = 500): Promise<string> {
  const { rows } = await client!.query(
    `INSERT INTO sync_sessions (team_id, member_id, source, session_id, model, tokens_in, tokens_out, payload_hash)
     VALUES ($1,$2,$3,$4,'m',$5,$6,'h') RETURNING id`,
    [team, member, source, sid, tokensIn, tokensOut],
  );
  return rows[0].id;
}
const events = (n: number) => Array.from({ length: n }, (_, i) => [
  { kind: 'user', text: `synthetic prompt ${i}` },
  { kind: 'assistant', text: `synthetic answer ${i}` },
]).flat();
const ingest = (t: string, m: string, src: string, sid: string, n: number, o = nested()) => saveSessionTurns(t, m, src, 'm', sid, events(n), o);
const turns = async (t: string, m: string, src: string, sid: string) =>
  (await client!.query('SELECT id::text, turn_index, turn_role, input_tokens, output_tokens FROM session_turns WHERE org_id=$1 AND user_id=$2 AND tool=$3 AND session_id=$4 ORDER BY id', [t, m, src, sid])).rows;
const sumIn = (rows: { turn_role: string; input_tokens: number }[]) => rows.filter((r) => r.turn_role === 'assistant').reduce((a, r) => a + Number(r.input_tokens), 0);

describe('session_turns tenant isolation (rolled-back temp tables)', { skip: SKIP_DB && SKIP_REASON }, () => {
  before(async () => {
    try {
      client = new pg.Client({ connectionString: connectionString(cfg!), ssl: { rejectUnauthorized: false } });
      await client.connect();
      await client.query('BEGIN');
      await client.query(`
        CREATE TEMP TABLE sync_sessions (LIKE public.sync_sessions INCLUDING ALL);
        CREATE TEMP TABLE sync_session_tools (LIKE public.sync_session_tools INCLUDING ALL);
        CREATE TEMP TABLE team_members (team_id uuid, member_id uuid);
        CREATE TEMP TABLE session_outcomes (session_id text NOT NULL, org_id text NOT NULL, user_id text NOT NULL, tool text NOT NULL, model text NOT NULL,
          intent_category text, total_input_tokens int, total_output_tokens int, total_cost numeric(12,4), files_touched int, lines_changed int,
          tool_call_count int, had_rework boolean, had_revert boolean, had_tool_error boolean, success boolean, complexity_score numeric,
          PRIMARY KEY (org_id, user_id, tool, session_id));
        CREATE TEMP TABLE session_turns (LIKE public.session_turns INCLUDING ALL EXCLUDING DEFAULTS);
        ALTER TABLE session_turns ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        CREATE TEMP TABLE session_tool_errors (LIKE public.session_tool_errors INCLUDING ALL EXCLUDING DEFAULTS);
        ALTER TABLE session_tool_errors ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        ALTER TABLE session_tool_errors ADD FOREIGN KEY (turn_id) REFERENCES session_turns(id) ON DELETE CASCADE;
        CREATE TEMP TABLE prompt_embeddings (turn_id bigint PRIMARY KEY REFERENCES session_turns(id), embedding float8[]);
        CREATE TEMP TABLE redundant_reprompt_events (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, session_id text NOT NULL, org_id text, user_id text, tool text,
          turn_index int NOT NULL, similarity_score numeric, tokens_cost_of_following_turn int, created_at timestamptz DEFAULT now());`);
      // Safety: unqualified names MUST resolve to the temp copies, never to the real tables.
      const { rows } = await client.query(`SELECT bool_and(to_regclass(t)::oid = to_regclass('pg_temp.' || t)::oid) AS ok
        FROM unnest(ARRAY['sync_sessions','sync_session_tools','team_members','session_turns','session_tool_errors','prompt_embeddings','redundant_reprompt_events','session_outcomes']) AS t`);
      assert.equal(rows[0].ok, true);
    } catch (err) {
      try { await client?.query('ROLLBACK'); await client?.end(); } catch { /* ignore */ }
      client = undefined;
      throw err; // an unreachable or mis-shaped test database is a FAILURE, never a silent skip
    }
  });
  after(async () => {
    if (client) { await client.query('ROLLBACK').catch(() => {}); await client.end().catch(() => {}); }
  });
  const t = (name: string, fn: () => Promise<void>) => it(name, fn);

  const isolation = (label: string, mk: () => { a: [string, string, string]; b: [string, string, string] }) =>
    t(label, async () => {
      const { a, b } = mk();
      const sid = `sid-${uuid()}`;
      await newSession(a[0], a[1], a[2], sid, 1000);
      await newSession(b[0], b[1], b[2], sid, 9000);
      await ingest(a[0], a[1], a[2], sid, 2);
      await ingest(b[0], b[1], b[2], sid, 2);
      const bBefore = await turns(b[0], b[1], b[2], sid);
      assert.equal(bBefore.length, 4);
      await ingest(a[0], a[1], a[2], sid, 3); // re-ingest A only, with a different number of turns
      assert.deepEqual(await turns(b[0], b[1], b[2], sid), bBefore); // B untouched: same rows, same ids, same values
      const aAfter = await turns(a[0], a[1], a[2], sid);
      assert.equal(aAfter.length, 6);
      // token allocation uses the correct parent: A's turns distribute A's 1000 tokens, B's distribute B's 9000
      assert.ok(Math.abs(sumIn(aAfter) - 1000) <= 3, `A allocation ${sumIn(aAfter)}`);
      assert.ok(Math.abs(sumIn(bBefore) - 9000) <= 3, `B allocation ${sumIn(bBefore)}`);
    });

  const [t1, t2, m1, m2] = [uuid(), uuid(), uuid(), uuid()];
  isolation('A: same session_id in two teams — re-ingesting one leaves the other unchanged', () => ({ a: [t1, m1, 'cursor'], b: [t2, m2, 'cursor'] }));
  isolation('B: same session_id for two members of one team — re-ingesting one leaves the other unchanged', () => ({ a: [t1, uuid(), 'cursor'], b: [t1, uuid(), 'cursor'] }));
  isolation('C: same session_id from two sources — re-ingesting one leaves the other unchanged', () => ({ a: [t1, m1, 'cursor'], b: [t1, m1, 'claude'] }));

  t('unknown parent session fails safely: nothing is deleted, no session_id-only fallback', async () => {
    const sid = `sid-${uuid()}`;
    const [team, member] = [uuid(), uuid()];
    await newSession(team, member, 'cursor', sid);
    await ingest(team, member, 'cursor', sid, 2);
    const before = await turns(team, member, 'cursor', sid);
    // same session_id exists, but not for this (team, member, source) identity
    await assert.rejects(() => ingest(team, uuid(), 'cursor', sid, 1), /parent session not found/);
    await assert.rejects(() => ingest(team, member, 'claude', sid, 1), /parent session not found/);
    await assert.rejects(() => saveSessionTurns('not-a-uuid', member, 'cursor', 'm', sid, events(1), nested()), /invalid session identity/);
    assert.deepEqual(await turns(team, member, 'cursor', sid), before);
  });

  t('D: deletion only touches the identified session and turn', async () => {
    const sid = `sid-${uuid()}`;
    const [ta, ma, tb, mb] = [uuid(), uuid(), uuid(), uuid()];
    await newSession(ta, ma, 'cursor', sid); await newSession(tb, mb, 'cursor', sid);
    await ingest(ta, ma, 'cursor', sid, 3); await ingest(tb, mb, 'cursor', sid, 3);
    const bBefore = await turns(tb, mb, 'cursor', sid);
    const aTurn = (await turns(ta, ma, 'cursor', sid)).find((r) => r.turn_role === 'user' && r.turn_index === 1)!;

    // team A deleting by session id + turn index: only A's turn 1 (user + assistant) goes
    const r1 = await deletePrompts({ kind: 'team', teamId: ta }, { ids: [], sessionId: sid, turnIndex: 1 }, nested());
    assert.equal(r1.deleted, 2);
    assert.equal((await turns(ta, ma, 'cursor', sid)).length, 4);
    assert.deepEqual(await turns(tb, mb, 'cursor', sid), bBefore);

    // team A cannot delete B's turn by id
    const bUser = bBefore.find((r) => r.turn_role === 'user')!;
    await assert.rejects(() => deletePrompts({ kind: 'team', teamId: ta }, { ids: [bUser.id], sessionId: null, turnIndex: null }, nested()),
      (e: unknown) => e instanceof PromptDeleteError && e.status === 403);
    assert.deepEqual(await turns(tb, mb, 'cursor', sid), bBefore);

    // id + sessionId + turnIndex together (what the UI sends): exactly the one turn, no 409 despite the collision
    const aUser = (await turns(ta, ma, 'cursor', sid)).find((r) => r.turn_role === 'user' && r.turn_index === 2)!;
    const r2 = await deletePrompts({ kind: 'team', teamId: ta }, { ids: [aUser.id], sessionId: sid, turnIndex: 2 }, nested());
    assert.equal(r2.deleted, 2);
    assert.deepEqual(await turns(tb, mb, 'cursor', sid), bBefore);
    void aTurn;

    // unscoped (platform) deletion by a bare, colliding session id is refused instead of wiping both owners
    await assert.rejects(() => deletePrompts({ kind: 'platform' }, { ids: [], sessionId: sid, turnIndex: null }, nested()),
      (e: unknown) => e instanceof PromptDeleteError && e.status === 409);
    assert.deepEqual(await turns(tb, mb, 'cursor', sid), bBefore);

    // team deletion of a whole session removes only that team's turns
    await deletePrompts({ kind: 'team', teamId: ta }, { ids: [], sessionId: sid, turnIndex: null }, nested());
    assert.equal((await turns(ta, ma, 'cursor', sid)).length, 0);
    assert.deepEqual(await turns(tb, mb, 'cursor', sid), bBefore);
  });

  t('D2: delete result reports the rows actually removed', async () => {
    const [team, member] = [uuid(), uuid()];
    const sid = `sid-${uuid()}`;
    await newSession(team, member, 'cursor', sid);
    await ingest(team, member, 'cursor', sid, 2); // 2 user + 2 assistant rows
    const none = await deletePrompts({ kind: 'team', teamId: team }, { ids: ['999999999'], sessionId: null, turnIndex: null }, nested()).catch((e) => e);
    assert.ok(none instanceof PromptDeleteError && none.status === 403); // nothing authorized: error, not a fake count
    const turn = await deletePrompts({ kind: 'platform' }, { ids: [], sessionId: sid, turnIndex: 0 }, nested());
    assert.deepEqual(turn, { deleted: 2, turns: 2, sessions: 0 });
    const gone = await deletePrompts({ kind: 'platform' }, { ids: [sid], sessionId: null, turnIndex: null }, nested());
    assert.deepEqual(gone, { deleted: 3, turns: 2, sessions: 1 }); // remaining 2 turn rows + the session row
    const missing = await deletePrompts({ kind: 'platform' }, { ids: [`sid-${uuid()}`], sessionId: null, turnIndex: null }, nested());
    assert.deepEqual(missing, { deleted: 0, turns: 0, sessions: 0 });
  });

  t('G: read-only diagnostics parse and detect seeded anomalies', async () => {
    const sql = fs.readFileSync('scripts/diagnostics/session-turns-integrity.sql', 'utf8');
    const queries = Object.fromEntries(sql.split(/^-- name: /m).slice(1).map((b) => [b.split('\n')[0].trim(), b.split('\n').slice(1).join('\n')]));
    for (const q of Object.values(queries)) assert.match(q, /^\s*(--.*\n|\s)*(WITH|SELECT)/i); // SELECT-only
    const [ta, ma, tb, mb] = [uuid(), uuid(), uuid(), uuid()];
    const dup = `sid-${uuid()}`;
    await newSession(ta, ma, 'cursor', dup, 1000); await newSession(tb, mb, 'cursor', dup, 1000);
    await ingest(ta, ma, 'cursor', dup, 2); await ingest(tb, mb, 'cursor', dup, 2);
    await client!.query('UPDATE sync_sessions SET tokens_in = 900000 WHERE team_id = $1 AND session_id = $2', [tb, dup]); // mismatching totals
    const orphan = `sid-${uuid()}`;
    await client!.query(`INSERT INTO session_turns (session_id, org_id, user_id, tool, model, turn_index, turn_role) VALUES ($1,$2,$3,'cursor','m',0,'user')`, [orphan, uuid(), uuid()]);
    const evOnly = `sid-${uuid()}`, evOld = `sid-${uuid()}`;
    const [te, me] = [uuid(), uuid()];
    await newSession(te, me, 'cursor', evOnly); await newSession(te, me, 'cursor', evOld);
    await client!.query(`UPDATE sync_sessions SET events = '[{"kind":"user","text":"x"}]'::jsonb WHERE team_id = $1`, [te]);
    await client!.query(`UPDATE sync_sessions SET synced_at = now() - interval '30 days' WHERE session_id = $1`, [evOld]);
    const imb = `sid-${uuid()}`;
    await newSession(te, me, 'claude', imb); await ingest(te, me, 'claude', imb, 2);
    await client!.query(`DELETE FROM session_turns WHERE session_id = $1 AND turn_role = 'assistant' AND turn_index = 1`, [imb]);
    const gone = `sid-${uuid()}`;
    await client!.query(`INSERT INTO session_outcomes (session_id, org_id, user_id, tool, model) VALUES ($1,$2,$3,'cursor','m')`, [gone, uuid(), uuid()]);
    await client!.query(`INSERT INTO redundant_reprompt_events (session_id, org_id, user_id, tool, turn_index) VALUES ($1,$2,$3,'cursor',0),($1,$2,$3,'cursor',0)`, [dup, ta, ma]);
    await client!.query(`INSERT INTO redundant_reprompt_events (session_id, turn_index) VALUES ($1,3)`, [dup]); // legacy row: NULL owner

    const run = async (name: string) => (await client!.query(queries[name])).rows as Record<string, unknown>[];
    assert.ok((await run('duplicate_session_ids')).some((r) => r.session_id === dup && Number(r.identities) === 2 && Number(r.teams) === 2));
    const orphans = await run('orphaned_turns');
    assert.ok(orphans.some((r) => r.session_id === orphan && r.session_id_exists_elsewhere === false));
    assert.ok(!orphans.some((r) => r.session_id === dup)); // healthy sessions are not flagged
    const noTurns = await run('sessions_with_events_but_no_turns');
    assert.equal(noTurns.find((r) => r.session_id === evOnly)?.likely_pruned, false);
    assert.equal(noTurns.find((r) => r.session_id === evOld)?.likely_pruned, true);
    assert.ok((await run('turn_role_imbalance')).some((r) => r.session_id === imb));
    const mism = await run('token_allocation_mismatch_on_duplicated_ids');
    assert.ok(mism.some((r) => r.session_id === dup && r.team_id === tb) && !mism.some((r) => r.team_id === ta && r.session_id === dup));
    assert.ok((await run('session_outcomes_without_parent')).some((r) => r.session_id === gone));
    const rq = await run('redundant_reprompt_events_quality');
    assert.ok(rq.some((r) => r.session_id === dup && r.org_id === ta && Number(r.copies) === 2)); // duplicated copies
    assert.ok(rq.some((r) => r.session_id === dup && r.org_id === null)); // NULL-owner legacy row
  });

  t('E: assistant token counts attach only to the matching session owner', async () => {
    const sid = `sid-${uuid()}`;
    const [ta, ma, tb, mb] = [uuid(), uuid(), uuid(), uuid()];
    await newSession(ta, ma, 'cursor', sid); await newSession(tb, mb, 'cursor', sid);
    const ins = (team: string, member: string, role: string, idx: number, tokens: number) => client!.query(
      `INSERT INTO session_turns (session_id, org_id, user_id, tool, model, turn_index, turn_role, input_tokens) VALUES ($1,$2,$3,'cursor','m',$4,$5,$6)`,
      [sid, team, member, idx, role, tokens]);
    for (const idx of [0, 1]) {
      await ins(ta, ma, 'user', idx, 0); await ins(ta, ma, 'assistant', idx, 111);
      await ins(tb, mb, 'user', idx, 0); await ins(tb, mb, 'assistant', idx, 222);
    }
    const list = (assistantJoin: string) => client!.query(
      `SELECT st.org_id, ast.input_tokens::int AS tokens FROM session_turns st
       JOIN sync_sessions ss ON ${SESSION_TURN_OWNER_JOIN}
       LEFT JOIN session_turns ast ON ${assistantJoin}
       WHERE st.turn_role = 'user' AND st.session_id = $1`, [sid]);
    const fixed = (await list(ASSISTANT_TURN_JOIN)).rows;
    assert.equal(fixed.length, 4); // one row per user turn — no cross-owner fan-out
    for (const r of fixed) assert.equal(r.tokens, r.org_id === ta ? 111 : 222);
    // control: the old join (session_id + turn_index only) fans out and mixes owners
    const legacy = (await list("ast.session_id = st.session_id AND ast.turn_index = st.turn_index AND ast.turn_role = 'assistant'")).rows;
    assert.equal(legacy.length, 8);
  });

  t('F: a failure while inserting turns rolls back — original turns remain, no partial replacement', async () => {
    const sid = `sid-${uuid()}`;
    const [team, member] = [uuid(), uuid()];
    await newSession(team, member, 'cursor', sid);
    await ingest(team, member, 'cursor', sid, 2);
    const before = await turns(team, member, 'cursor', sid);
    let inserts = 0;
    const failing: Queryable = {
      query: ((text: string, params?: unknown[]) => {
        if (/INSERT INTO session_turns/.test(text) && ++inserts === 2) return Promise.reject(new Error('simulated insert failure'));
        return client!.query(text, params);
      }) as never,
    };
    await assert.rejects(() => saveSessionTurns(team, member, 'cursor', 'm', sid, events(5), { executor: failing, nested: true }), /simulated insert failure/);
    assert.equal(inserts, 2); // the user rows were inserted before the failure…
    assert.deepEqual(await turns(team, member, 'cursor', sid), before); // …and are gone, with the old rows (same ids) restored
  });
});
